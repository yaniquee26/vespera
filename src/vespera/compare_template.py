"""HTML template of the two-model comparison page."""

from vespera.report_template import TEMPLATE

# Reuse the look of the single-run report so both pages feel like one product.
_STYLE = TEMPLATE.split("<style>")[1].split("</style>")[0]

_EXTRA_STYLE = """
.bar.b .ci { background: var(--accent); opacity: 0.3; }
.bar.b .pt { background: var(--accent); }
.who { display: inline-block; width: 1.4em; font-weight: 700; }
.pair { padding: 3px 0; }
.legend span { margin-right: 16px; }
"""

_BAR = """<div class="pair"><span class="who">{who}</span>
  <span class="num">{{{{ {r}.k }}}} / {{{{ {r}.n }}}} ({{{{ {r}.p | pct }}}})</span>
  <div class="bar{cls}" role="img"
    aria-label="Model {who}: {{{{ {r}.p | pct }}}}, interval {{{{ {r}.low | pct }}}} to {{{{ {r}.high | pct }}}}">
    <div class="ci" style="left: {{{{ {r}.low | w }}}}%; width: {{{{ ({r}.high - {r}.low) | w }}}}%"></div>
    <div class="pt" style="left: {{{{ {r}.p | w }}}}%"></div></div>
  <span class="muted">{{{{ {r}.low | pct }}}} to {{{{ {r}.high | pct }}}}</span></div>"""


def _bars(prefix: str) -> str:
    a = _BAR.format(who="A", r=f"{prefix}.a", cls="")
    b = _BAR.format(who="B", r=f"{prefix}.b", cls=" b")
    return a + "\n" + b


